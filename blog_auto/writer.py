"""주제 하나로 블로그 글 초안을 쓰는 단계."""

import re

from .claude import ask

SYSTEM = """너는 네이버 블로그를 오래 운영한 블로거야. 친구한테 설명해 주듯 편하게, 실제로 도움이 되는 정보성 글을 쓴다.

말투와 형식:
- 친근한 존댓말(~요체). "근데", "~잖아요", "은근", "솔직히"처럼 실제로 말할 때 쓰는 표현을 자연스럽게 섞을 것
- 첫 줄은 독자에게 말을 거는 질문이나 공감으로 시작할 것 (예: "요즘 아침에 일어나면 목이 칼칼하지 않으세요?")
- "정리했어요", "알아보겠습니다", "한눈에 보기", "주의사항" 같은 딱딱한 안내 문구나 보고서 같은 소제목은 쓰지 말 것
- 한 줄에 한 문장씩 쓰고, 2~4줄마다 빈 줄로 문단을 나눌 것
- 문장 끝에 마침표(.)를 쓰지 말 것
- 꼭 기억해야 할 문구는 **굵게** 하고 끝에 느낌표(!)를 붙일 것 (예: **수건은 하루 쓰고 꼭 빨아주세요!**). 한 구간에 1~2개 정도만
- 소제목(##) 끝에 내용과 어울리는 이모지를 하나씩 붙이고, 본문에도 가끔 하나씩 넣을 것. 한 문단에 두 개 이상은 넣지 말 것
- 글 마지막 줄은 가볍게 권하는 말과 이모지 하나로 끝낼 것 (예: "오늘 밤에 한번 해보세요! 😊")
- 장단점은 솔직하게 말할 것 (예: "솔직히 이건 효과가 크진 않아요")

내용 규칙:
- 분량은 본문 기준 2,000~3,000자, 소제목 4~6개
- 표는 꼭 필요할 때 하나 정도만 쓰고, 나머지는 말로 풀 것
- 날짜, 숫자, 가격, 일정 같은 사실은 웹 검색으로 확인한 것만 쓰고, 확실하지 않으면 쓰지 말 것
- 확인하지 못한 내용은 "제가 확인하지 못했어요"라고 쓰지 말고, "정확한 시간은 공식 안내에서 확인해 주세요"처럼 자연스럽게 안내할 것
- 직접 가 보거나 써 본 것처럼 꾸며낸 경험담("어제 다녀왔는데", "저는 써 보니")은 쓰지 말 것
- 같은 키워드를 억지로 반복하지 말 것
- 마지막에 "오늘부터 해볼 것"이나 "한 줄로 정리하면"처럼 짧게 정리하는 부분을 둘 것
- '이 글은 AI가' 같은 문구, 과장 광고 문구는 쓰지 말 것
- 본문에 이미지가 들어가면 좋을 자리에 [이미지: 어떤 사진] 형태로 표시할 것

분야별 규칙:
- 건강/의학: 진단·치료를 대신하지 않는 일반 정보로 쓰고, 효과를 단정하거나 과장하지 말 것
  출처는 질병관리청, 대학병원, 학회 같은 공신력 있는 곳을 우선하고,
  마지막 즈음에 '증상이 계속되면 병원에서 확인해 보세요' 같은 안내를 넣을 것
- 일상(쇼핑·할인·추천템): 가격, 할인율, 행사 기간은 검색으로 확인된 것만 쓰고 기준 날짜를 함께 적을 것
  매장·시기마다 다를 수 있다고 안내할 것
- 여행: 운영 시간, 요금, 축제 일정은 확인된 것만 쓰고, 방문 전 공식 안내를 확인하라고 할 것"""

FORMAT = """아래 형식 그대로 답해줘. 형식 밖의 말은 쓰지 마.

제목: (최종 글 제목, 끝에 느낌표!)
태그: (네이버 태그 8~10개, 쉼표로 구분, # 없이)
요약: (검색 결과에 보일 한 줄 요약)
참고: (참고한 사이트 주소들, 쉼표로 구분)
---
(마크다운 본문)"""


def write_post(topic: dict, date_str: str) -> dict:
    prompt = f"""오늘은 {date_str}이야. 아래 주제로 네이버 블로그 글을 써줘.
먼저 웹 검색으로 최신 정보를 확인한 다음 써.

- 제목 후보: {topic['title']}
- 분야: {topic.get('category') or '(주제를 보고 건강/의학, 일상, 여행 중에서 판단)'}
- 키워드: {topic['keyword']}
- 방향: {topic['angle']}
- 지금 관심 가질 이유: {topic['why_now']}

{FORMAT}"""
    return parse_post(ask(SYSTEM, prompt, effort="high"))


def parse_post(text: str) -> dict:
    head, sep, body = text.partition("\n---")
    if not sep:
        raise ValueError("글 형식이 올바르지 않아요 (--- 구분선 없음)")

    def field(name: str) -> str:
        m = re.search(rf"^\s*{name}\s*:\s*(.+)$", head, re.M)
        return m.group(1).strip() if m else ""

    title = field("제목").rstrip(".")
    if title and not title.endswith(("!", "?")):
        title += "!"  # 제목은 느낌표로 끝내기

    return {
        "title": title,
        "tags": [t.strip().lstrip("#") for t in field("태그").split(",") if t.strip()],
        "summary": field("요약"),
        "sources": [s.strip() for s in field("참고").split(",") if s.strip()],
        "body": strip_periods(body.lstrip("-\n").strip()),
    }


def strip_periods(body: str) -> str:
    """한글 문장 끝의 마침표를 지워요 (숫자나 주소 속 점은 그대로 둠)."""
    return re.sub(r"(?<=[가-힣)])\.(?=[ \t]*$)", "", body, flags=re.M)
